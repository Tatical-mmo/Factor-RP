-- comprar: igual ao de antes, mas casa da favela alugada por outro não pode ser comprada
create or replace function public.comprar_casa(p_casa integer) returns void
language plpgsql security definer set search_path = public as $$
declare p perfis%rowtype; c casas%rowtype;
begin
  p := jogador_livre();
  select * into p from perfis where id = p.id for update;
  select * into c from casas where id = p_casa for update;
  if c.id is null or c.tipo in ('unidade', 'oficial') then raise exception 'casa invalida'; end if;
  if c.dono is not null then raise exception 'casa ja vendida'; end if;
  if c.tipo = 'favela' and c.inquilino is not null and c.pago_ate > now() and c.inquilino <> p.id then raise exception 'casa alugada'; end if;
  if total_moradias(p.id) >= 3 and not (c.inquilino = p.id and c.pago_ate > now()) then raise exception 'limite de 3 moradias'; end if;
  if p.moedas < c.preco then raise exception 'moedas insuficientes'; end if;
  update perfis set moedas = moedas - c.preco where id = p.id;
  update casas set dono = p.id, inquilino = null, pago_ate = null where id = c.id;
end $$;

-- alugar (ou renovar) casa da favela: o dinheiro vai para a prefeitura
create or replace function public.alugar_casa_favela(p_casa integer) returns timestamptz
language plpgsql security definer set search_path = public as $$
declare p perfis%rowtype; c casas%rowtype; ate timestamptz; renova boolean;
begin
  p := jogador_livre();
  select * into p from perfis where id = p.id for update;
  select * into c from casas where id = p_casa and tipo = 'favela' for update;
  if c.id is null then raise exception 'casa invalida'; end if;
  if c.dono is not null then raise exception 'casa ja vendida'; end if;
  renova := c.inquilino = p.id and c.pago_ate > now();
  if c.inquilino is not null and c.pago_ate > now() and not renova then raise exception 'casa alugada'; end if;
  if not renova and total_moradias(p.id) >= 3 then raise exception 'limite de 3 moradias'; end if;
  if p.moedas < c.aluguel then raise exception 'moedas insuficientes'; end if;
  if c.inquilino is not null and c.inquilino <> p.id then perform devolver_bau(c.id, c.inquilino); end if;
  update perfis set moedas = moedas - c.aluguel where id = p.id;
  update prefeitura set cofre = cofre + c.aluguel where id = 1;
  update casas set inquilino = p.id, pago_ate = (case when renova then pago_ate else now() end) + make_interval(secs => 15 * 1920)
    where id = c.id returning pago_ate into ate;
  return ate;
end $$;

-- vender: casa da favela devolve metade do preço
create or replace function public.vender_casa(p_casa integer) returns integer
language plpgsql security definer set search_path = public as $$
declare c casas%rowtype; valor integer; k integer;
begin
  select * into c from casas where id = p_casa and dono = auth.uid() for update;
  if c.id is null then raise exception 'essa moradia nao e sua'; end if;
  if c.tipo = 'oficial' then raise exception 'a residencia oficial e do cargo: para sair, renuncie'; end if;
  if c.tipo = 'terreno' and exists (select 1 from casas where pai = c.id and (dono is not null or (inquilino is not null and pago_ate > now()))) then
    raise exception 'ha apartamentos vendidos ou alugados neste predio';
  end if;
  perform devolver_bau(c.id, auth.uid());
  if c.tipo = 'unidade' then
    valor := c.preco / 2;
    update casas set dono = null, a_venda = false, preco = 0 where id = c.id;
  elsif c.tipo = 'favela' then
    valor := c.preco / 2;
    update casas set dono = null where id = c.id;
  else
    valor := case c.tipo when 'apto' then 8000 when 'terreno' then 6000 + coalesce(preco_modelo(c.modelo), 0) / 2 else 20000 end;
    if c.tipo = 'terreno' then for k in 1..c.nivel - 1 loop valor := valor + imovel(k, 'evoluir') / 2; end loop; end if;
    delete from casas where pai = c.id;
    update casas set dono = null, modelo = null, nivel = 1 where id = c.id;
  end if;
  update perfis set moedas = moedas + valor where id = auth.uid();
  return valor;
end $$;

-- aluguéis vencidos: apartamentos (como antes) e casas da favela (renova sozinho a cada 15 ciclos se tiver dinheiro)
create or replace function public.processar_alugueis() returns integer
language plpgsql security definer set search_path = public as $$
declare u casas%rowtype; dono_predio uuid; n integer := 0; pago integer;
begin
  for u in select * from casas where tipo = 'unidade' and inquilino is not null and pago_ate <= now() for update skip locked loop
    select dono into dono_predio from casas where id = u.pai;
    pago := 0;
    if u.aluguel is not null and dono_predio is not null and u.dono is null then
      update perfis set moedas = moedas - u.aluguel where id = u.inquilino and moedas >= u.aluguel;
      get diagnostics pago = row_count;
    end if;
    if pago > 0 then
      update perfis set moedas = moedas + u.aluguel where id = dono_predio;
      update casas set pago_ate = greatest(pago_ate, now()) + interval '1 day' where id = u.id;
    else
      perform devolver_bau(u.id, u.inquilino);
      perform avisar(u.inquilino, format('Seu aluguel em %s venceu e você saiu do apartamento.', u.rotulo));
      update casas set inquilino = null, pago_ate = null where id = u.id;
    end if;
    n := n + 1;
  end loop;
  for u in select * from casas where tipo = 'favela' and inquilino is not null and pago_ate <= now() for update skip locked loop
    update perfis set moedas = moedas - u.aluguel where id = u.inquilino and moedas >= u.aluguel;
    get diagnostics pago = row_count;
    if pago > 0 and u.dono is null then
      update prefeitura set cofre = cofre + u.aluguel where id = 1;
      update casas set pago_ate = greatest(pago_ate, now()) + make_interval(secs => 15 * 1920) where id = u.id;
    else
      perform devolver_bau(u.id, u.inquilino);
      perform avisar(u.inquilino, format('O aluguel da %s venceu e você saiu da casa.', u.rotulo));
      update casas set inquilino = null, pago_ate = null where id = u.id;
    end if;
    n := n + 1;
  end loop;
  return n;
end $$;

-- administrador: preço de compra e aluguel das casas da favela (vale para as que ainda não foram vendidas)
create or replace function public.admin_favela_precos(p_preco integer, p_aluguel integer) returns void
language plpgsql security definer set search_path = public as $$
begin
  if (select cargo from perfis where id = auth.uid()) is distinct from 'admin' then raise exception 'so o administrador'; end if;
  if p_preco is null or p_preco < 1000 or p_preco > 5000000 then raise exception 'preco entre 1000 e 5000000'; end if;
  if p_aluguel is null or p_aluguel < 50 or p_aluguel > 50000 then raise exception 'aluguel entre 50 e 50000'; end if;
  update config_jogo set favela_preco = p_preco, favela_aluguel = p_aluguel, atualizado = now() where id = 1;
  update casas set preco = p_preco, aluguel = p_aluguel where tipo = 'favela' and dono is null;
  perform registrar(null, 'favela_precos', jsonb_build_object('preco', p_preco, 'aluguel', p_aluguel));
end $$;

